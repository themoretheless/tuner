// Generates web/src/generated/gateThresholds.ts from the canonical gate
// constants in the Rust pitch-core sources. Rust is the single source of
// truth; the TypeScript fallback detector cannot depend on the WASM module
// (it must run when the module fails to load), so it consumes this generated
// mirror instead. Run with --check to verify the mirror is in lockstep.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const detectorSource = await readFile(resolve(root, 'pitch-core/src/dsp/detector.rs'), 'utf8');
const gateSource = await readFile(resolve(root, 'pitch-core/src/gate.rs'), 'utf8');

const fixedGate = [
  ['FIXED_GATE_RMS', 'rmsGate'],
  ['FIXED_GATE_PEAK', 'peakGate'],
  ['MIN_USABLE_CONFIDENCE', 'minUsableConfidence'],
  ['DEFAULT_YIN_THRESHOLD', 'yinThreshold'],
].map(([rustName, tsName]) => [tsName, parseConstant(detectorSource, rustName)]);

const adaptiveGate = [
  ['CALIBRATION_FRAMES', 'calibrationFrames'],
  ['CLOSE_CONFIRM_FRAMES', 'closeConfirmFrames'],
  ['OPEN_NOISE_RATIO', 'openNoiseRatio'],
  ['CLOSE_NOISE_RATIO', 'closeNoiseRatio'],
  ['OPEN_BASE_RMS_FACTOR', 'openBaseRmsFactor'],
  ['CLOSE_BASE_RMS_FACTOR', 'closeBaseRmsFactor'],
  ['CLOSE_PEAK_FACTOR', 'closePeakFactor'],
  ['STRONG_ATTACK_RMS', 'strongAttackRms'],
  ['STRONG_ATTACK_PEAK', 'strongAttackPeak'],
  ['ONSET_RATIO', 'onsetRatio'],
  ['ONSET_RMS_DELTA', 'onsetRmsDelta'],
  ['UNIVERSAL_CONFIDENCE', 'universalConfidence'],
  ['TARGET_CONFIDENCE', 'targetConfidence'],
  ['TARGET_DISTANCE_CENTS', 'targetDistanceCents'],
  ['NOISE_FLOOR_DECAY', 'noiseFloorDecay'],
  ['NOISE_FLOOR_UPDATE_WEIGHT', 'noiseFloorUpdateWeight'],
  ['NOISE_FLOOR_CAP_FACTOR', 'noiseFloorCapFactor'],
].map(([rustName, tsName]) => [tsName, parseConstant(gateSource, rustName)]);

const source = generateTypeScript();
const target = resolve(root, 'web/src/generated/gateThresholds.ts');

if (process.argv.includes('--check')) {
  const current = normalizeLineEndings(await readFile(target, 'utf8').catch(() => ''));
  if (current !== source) {
    throw new Error(`${target} is stale; run: node scripts/generate-gate-thresholds.mjs`);
  }
} else {
  await writeFile(target, source);
}

function parseConstant(rustSource, name) {
  const pattern = new RegExp(`const ${name}: (?:f32|u8) = ([0-9][0-9._]*);`);
  const match = rustSource.match(pattern);
  if (!match) {
    throw new Error(`gate constant ${name} not found in Rust source; rename it in this script too`);
  }
  const value = Number(match[1].replaceAll('_', ''));
  if (!Number.isFinite(value)) {
    throw new Error(`gate constant ${name} has a non-numeric value: ${match[1]}`);
  }
  return value;
}

function normalizeLineEndings(value) {
  return value.replaceAll('\r\n', '\n');
}

function generateTypeScript() {
  const fixed = fixedGate.map(([name, value]) => `  ${name}: ${value},`).join('\n');
  const adaptive = adaptiveGate.map(([name, value]) => `    ${name}: ${value},`).join('\n');
  return `// @generated by scripts/generate-gate-thresholds.mjs. Do not edit manually.
// Source of truth: pitch-core/src/dsp/detector.rs (fixed detector gate) and
// pitch-core/src/gate.rs (adaptive signal gate). The same values are exposed
// at runtime by the WASM export coreGateThresholds().

export const GATE_THRESHOLDS = {
${fixed}
  adaptive: {
${adaptive}
  },
} as const;
`;
}
