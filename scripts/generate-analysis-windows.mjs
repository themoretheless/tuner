// Generates web/src/generated/analysisWindows.ts from the canonical
// multi-window ("lane") constants in the Rust pitch-core sources. Rust is the
// single source of truth; the TypeScript fallback detector cannot depend on
// the WASM module (it must run when the module fails to load), so it consumes
// this generated mirror instead. Run with --check to verify the mirror is in
// lockstep.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const windowsSource = await readFile(resolve(root, 'pitch-core/src/windows.rs'), 'utf8');

const standardWindows = parseWindowArray(windowsSource, 'STANDARD_ANALYSIS_WINDOWS');
const constants = [
  ['DEFAULT_WINDOW_SAMPLES', 'defaultWindowSamples'],
  ['HYSTERESIS_CENTS', 'hysteresisCents'],
  ['MIN_LANE_WINDOW_SAMPLES', 'minLaneWindowSamples'],
  ['MIN_PERIODS_IN_WINDOW', 'minPeriodsInWindow'],
  ['SWITCH_CENTER_RATIO', 'switchCenterRatio'],
].map(([rustName, tsName]) => [tsName, parseConstant(windowsSource, rustName)]);

const source = generateTypeScript();
const target = resolve(root, 'web/src/generated/analysisWindows.ts');

if (process.argv.includes('--check')) {
  const current = normalizeLineEndings(await readFile(target, 'utf8').catch(() => ''));
  if (current !== source) {
    throw new Error(`${target} is stale; run: node scripts/generate-analysis-windows.mjs`);
  }
} else {
  await writeFile(target, source);
}

function parseConstant(rustSource, name) {
  const pattern = new RegExp(`const ${name}: (?:f32|usize) = ([0-9][0-9._]*);`);
  const match = rustSource.match(pattern);
  if (!match) {
    throw new Error(`window constant ${name} not found in Rust source; rename it in this script too`);
  }
  const value = Number(match[1].replaceAll('_', ''));
  if (!Number.isFinite(value)) {
    throw new Error(`window constant ${name} has a non-numeric value: ${match[1]}`);
  }
  return value;
}

function parseWindowArray(rustSource, name) {
  const pattern = new RegExp(`const ${name}: \\[usize; \\d+\\] = \\[([0-9_,\\s]+)\\];`);
  const match = rustSource.match(pattern);
  if (!match) {
    throw new Error(`window array ${name} not found in Rust source; rename it in this script too`);
  }
  const windows = match[1]
    .split(',')
    .map((entry) => Number(entry.trim().replaceAll('_', '')))
    .filter((entry) => Number.isFinite(entry));
  if (windows.length === 0) {
    throw new Error(`window array ${name} parsed to an empty list: ${match[1]}`);
  }
  return windows;
}

function normalizeLineEndings(value) {
  return value.replaceAll('\r\n', '\n');
}

function generateTypeScript() {
  const entries = constants.map(([name, value]) => `  ${name}: ${value},`);
  entries.push(`  standardWindows: [${standardWindows.join(', ')}],`);
  entries.sort();
  return `// @generated by scripts/generate-analysis-windows.mjs. Do not edit manually.
// Source of truth: pitch-core/src/windows.rs (multi-window lane selection).
// The same lane set is exposed at runtime by the WASM export
// standardAnalysisWindows().

export const ANALYSIS_WINDOWS = {
${entries.join('\n')}
} as const;
`;
}
