import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const registry = JSON.parse(await readFile(resolve(root, 'registry/music-registry.json'), 'utf8'));
validateNoteNames(registry.noteNames);
const formulas = {
  applyCents: ['mul', 'frequency', ['pow2', ['div', 'cents', 1200]]],
  cents: ['mul', 1200, ['log2', ['div', 'frequency', 'target_frequency']]],
  distance: ['abs', ['log2', ['div', 'frequency', ['mul', 'target_frequency', 'scale']]]],
  frequencyToMidi: ['add', 69, ['mul', 12, ['log2', ['div', 'frequency', 'a4']]]],
  midiToFrequency: ['mul', 'a4', ['pow2', ['div', ['sub', 'midi', 69], 12]]],
};
const targets = [
  [resolve(root, 'pitch-core/src/generated_note_math.rs'), generateRust()],
  [resolve(root, 'web/src/generated/noteMath.ts'), generateTypeScript()],
];
const checkOnly = process.argv.includes('--check');

for (const [path, source] of targets) {
  if (checkOnly) {
    const current = normalizeLineEndings(await readFile(path, 'utf8').catch(() => ''));
    if (current !== source) {
      throw new Error(`${path} is stale; run: node scripts/generate-note-math.mjs`);
    }
    continue;
  }
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, source);
}

function expression(node, language) {
  if (typeof node === 'string') return node;
  if (typeof node === 'number') return language === 'rust' ? `${node}.0_f32` : String(node);
  const [operator, ...operands] = node;
  const values = operands.map((operand) => expression(operand, language));
  if (operator === 'pow2') {
    return language === 'rust'
      ? `2.0_f32.powf(${withoutOuterParentheses(values[0])})`
      : `Math.pow(2, ${values[0]})`;
  }
  if (operator === 'log2') {
    return language === 'rust' ? `${values[0]}.log2()` : `Math.log2(${values[0]})`;
  }
  if (operator === 'abs') {
    return language === 'rust' ? `${values[0]}.abs()` : `Math.abs(${values[0]})`;
  }
  const token = { add: '+', div: '/', mul: '*', sub: '-' }[operator];
  if (!token) throw new Error(`Unknown expression operator: ${operator}`);
  return `(${values.join(` ${token} `)})`;
}

function withoutOuterParentheses(value) {
  return value.startsWith('(') && value.endsWith(')') ? value.slice(1, -1) : value;
}

function normalizeLineEndings(value) {
  return value.replaceAll('\r\n', '\n');
}

function validateNoteNames(noteNames) {
  if (!Array.isArray(noteNames) || noteNames.length !== 12) {
    throw new Error('music registry must define exactly 12 note names');
  }
  if (noteNames.some((name) => typeof name !== 'string' || name.length === 0)) {
    throw new Error('music registry note names must be non-empty strings');
  }
  if (new Set(noteNames).size !== noteNames.length) {
    throw new Error('music registry note names must be unique');
  }
}

function generateRust() {
  const noteNames = `    ${registry.noteNames.map((name) => JSON.stringify(name)).join(', ')},`;
  const midiToFrequency = withoutOuterParentheses(expression(formulas.midiToFrequency, 'rust'));
  const frequencyToMidi = withoutOuterParentheses(expression(formulas.frequencyToMidi, 'rust'));
  const cents = withoutOuterParentheses(expression(formulas.cents, 'rust'));
  const applyCents = withoutOuterParentheses(expression(formulas.applyCents, 'rust'));
  const distance = expression(formulas.distance, 'rust');
  return `// @generated by scripts/generate-note-math.mjs. Do not edit manually.

pub const NOTE_NAMES: [&str; ${registry.noteNames.length}] = [
${noteNames}
];

pub fn canonical_note_name(name: &str) -> Option<&'static str> {
    NOTE_NAMES
        .iter()
        .copied()
        .find(|candidate| *candidate == name)
}

pub fn note_name_index(name: &str) -> Option<usize> {
    NOTE_NAMES.iter().position(|candidate| *candidate == name)
}

pub fn note_name_from_midi(midi: i32) -> &'static str {
    NOTE_NAMES[midi.rem_euclid(NOTE_NAMES.len() as i32) as usize]
}

pub fn octave_from_midi(midi: i32) -> i32 {
    midi.div_euclid(NOTE_NAMES.len() as i32) - 1
}

pub fn note_to_midi(name: &str, octave: i32) -> i32 {
    (octave + 1) * NOTE_NAMES.len() as i32 + note_name_index(name).unwrap_or(0) as i32
}

pub fn midi_to_frequency(midi: f32, a4: f32) -> f32 {
    if !midi.is_finite() || !a4.is_finite() || a4 <= 0.0 {
        return 0.0;
    }
    ${midiToFrequency}
}

pub fn frequency_to_midi(frequency: f32, a4: f32) -> f32 {
    if !frequency.is_finite() || frequency <= 0.0 || !a4.is_finite() || a4 <= 0.0 {
        return 0.0;
    }
    ${frequencyToMidi}
}

pub fn frequency_to_nearest_midi(frequency: f32, a4: f32) -> i32 {
    frequency_to_midi(frequency, a4).round() as i32
}

pub fn get_cents(frequency: f32, target_frequency: f32) -> f32 {
    if !frequency.is_finite()
        || frequency <= 0.0
        || !target_frequency.is_finite()
        || target_frequency <= 0.0
    {
        return 0.0;
    }
    ${cents}
}

pub fn apply_cents_offset_frequency(frequency: f32, cents: f32) -> f32 {
    if !frequency.is_finite() || frequency <= 0.0 || !cents.is_finite() {
        return frequency;
    }
    ${applyCents}
}

pub fn format_note_display(name: &str, octave: i32) -> String {
    format!("{name}{octave}")
}

pub fn format_freq(frequency: f32) -> String {
    format!("{frequency:.1}")
}

pub fn closest_frequency_index<I>(
    frequency: f32,
    target_frequencies: I,
    scale: f32,
) -> Option<usize>
where
    I: IntoIterator<Item = f32>,
{
    if !frequency.is_finite() || frequency <= 0.0 || !scale.is_finite() || scale <= 0.0 {
        return None;
    }
    target_frequencies
        .into_iter()
        .enumerate()
        .filter(|(_, target_frequency)| target_frequency.is_finite() && *target_frequency > 0.0)
        .min_by(|(_, left), (_, right)| {
            let target_frequency = *left;
            let left_distance = ${distance};
            let target_frequency = *right;
            let right_distance = ${distance};
            left_distance.total_cmp(&right_distance)
        })
        .map(|(index, _)| index)
}
`;
}

function generateTypeScript() {
  const midiToFrequency = expression(formulas.midiToFrequency, 'typescript');
  const frequencyToMidi = expression(formulas.frequencyToMidi, 'typescript');
  const cents = expression(formulas.cents, 'typescript').replaceAll('target_frequency', 'targetFrequency');
  const applyCents = expression(formulas.applyCents, 'typescript');
  const distance = expression(formulas.distance, 'typescript').replaceAll('target_frequency', 'targetFrequency');
  return `// @generated by scripts/generate-note-math.mjs. Do not edit manually.

export const NOTE_NAMES = ${JSON.stringify(registry.noteNames)} as const;
export type GeneratedNoteName = typeof NOTE_NAMES[number];

export interface FrequencyTarget {
  frequency: number;
}

export function canonicalNoteName(name: string): GeneratedNoteName | null {
  return NOTE_NAMES.find((candidate) => candidate === name) ?? null;
}

export function noteNameIndex(name: string): number {
  return NOTE_NAMES.findIndex((candidate) => candidate === name);
}

export function noteNameFromMidi(midi: number): GeneratedNoteName {
  return NOTE_NAMES[((midi % NOTE_NAMES.length) + NOTE_NAMES.length) % NOTE_NAMES.length];
}

export function octaveFromMidi(midi: number): number {
  return Math.floor(midi / NOTE_NAMES.length) - 1;
}

export function noteToMidi(name: string, octave: number): number {
  return (octave + 1) * NOTE_NAMES.length + Math.max(0, noteNameIndex(name));
}

export function midiToFrequency(midi: number, a4: number): number {
  if (!Number.isFinite(midi) || !Number.isFinite(a4) || a4 <= 0) return 0;
  return ${midiToFrequency};
}

export function frequencyToMidi(frequency: number, a4: number): number {
  if (!Number.isFinite(frequency) || frequency <= 0 || !Number.isFinite(a4) || a4 <= 0) return 0;
  return ${frequencyToMidi};
}

export function frequencyToNearestMidi(frequency: number, a4: number): number {
  return Math.round(frequencyToMidi(frequency, a4));
}

export function getCents(frequency: number, targetFrequency: number): number {
  if (!Number.isFinite(frequency) || frequency <= 0 || !Number.isFinite(targetFrequency) || targetFrequency <= 0) return 0;
  return ${cents};
}

export function applyCentsOffsetFrequency(frequency: number, cents: number): number {
  if (!Number.isFinite(frequency) || frequency <= 0 || !Number.isFinite(cents)) return frequency;
  return ${applyCents};
}

export function getNoteDisplay(note: { name: string; octave: number }): string {
  return \`\${note.name}\${note.octave}\`;
}

export function formatFreq(frequency: number): string {
  return frequency.toFixed(1);
}

export function closestNoteIndex(frequency: number, targets: readonly FrequencyTarget[], scale = 1): number | null {
  if (!Number.isFinite(frequency) || frequency <= 0 || !Number.isFinite(scale) || scale <= 0) return null;
  let closestIndex: number | null = null;
  let minimumDistance = Number.POSITIVE_INFINITY;
  targets.forEach((target, index) => {
    const targetFrequency = target.frequency;
    if (!Number.isFinite(targetFrequency) || targetFrequency <= 0) return;
    const distance = ${distance};
    if (distance < minimumDistance) {
      minimumDistance = distance;
      closestIndex = index;
    }
  });
  return closestIndex;
}
`;
}
